import { useRef, useState } from "react";
import { list } from "../api";

export function Badge({ value }) {
  const cls = String(value || "").toLowerCase().replace(/\s+/g, "-");
  return <span className={`badge ${cls}`}>{value || "n/a"}</span>;
}

export function Kpi({ label, value }) {
  return (
    <div className="kpi">
      <div className="label">{label}</div>
      <div className="value">{value}</div>
    </div>
  );
}

export function Meter({ value, max = 100 }) {
  const pct = Math.max(0, Math.min(100, (Number(value) / max) * 100 || 0));
  return (
    <div className="meter" aria-label={`${Math.round(pct)}%`}>
      <span style={{ width: `${pct}%` }} />
    </div>
  );
}

export function Bullets({ title, items, emptyText = "None reported." }) {
  const arr = list(items);
  return (
    <div>
      {title && <h3>{title}</h3>}
      {arr.length === 0 ? <p className="empty">{emptyText}</p> : (
        <ul>{arr.map((it, i) => <li key={i}>{String(it)}</li>)}</ul>
      )}
    </div>
  );
}

export function ErrorBox({ error }) {
  if (!error) return null;
  return (
    <div className="alert" role="alert">
      <strong>{error.message || "Something went wrong."}</strong>
      {list(error.errors).length > 0 && (
        <ul>{error.errors.map((e, i) => <li key={i}>{e.field ? `${e.field}: ` : ""}{e.message}</li>)}</ul>
      )}
    </div>
  );
}

export function MetaNote({ meta }) {
  if (!meta) return null;
  const demo = meta.ai_generated === false;
  return (
    <div className="meta-note">
      {demo ? "Demo / fallback response" : `AI-generated by ${meta.model || "model"}`}
      {list(meta.notes).length > 0 && ` · ${meta.notes.join("; ")}`}
      {" · "}Indicative only. Verify with a qualified professional.
    </div>
  );
}

export function SubmitButton({ loading, children }) {
  return (
    <button className="btn" type="submit" disabled={loading}>
      {loading && <span className="spinner" aria-hidden="true" />}
      {loading ? "Analysing..." : children}
    </button>
  );
}

export function ImageDrop({ file, onChange }) {
  const inputRef = useRef(null);
  const [active, setActive] = useState(false);
  const [preview, setPreview] = useState(null);

  const pick = (f) => {
    if (!f) return;
    if (!f.type.startsWith("image/")) {
      alert("Please choose a JPEG, PNG, WEBP or GIF image.");
      return;
    }
    onChange(f);
    const reader = new FileReader();
    reader.onload = (e) => setPreview(e.target.result);
    reader.readAsDataURL(f);
  };

  const clear = (e) => {
    e.stopPropagation();
    onChange(null);
    setPreview(null);
    if (inputRef.current) inputRef.current.value = "";
  };

  return (
    <div
      className={`dropzone ${active ? "active" : ""}`}
      onClick={() => inputRef.current?.click()}
      onDragOver={(e) => { e.preventDefault(); setActive(true); }}
      onDragLeave={() => setActive(false)}
      onDrop={(e) => { e.preventDefault(); setActive(false); pick(e.dataTransfer.files?.[0]); }}
      role="button" tabIndex={0}
      onKeyDown={(e) => e.key === "Enter" && inputRef.current?.click()}
    >
      <input ref={inputRef} type="file" accept="image/*" hidden onChange={(e) => pick(e.target.files?.[0])} />
      {file ? (
        <>
          <div>{file.name} ({(file.size / 1024).toFixed(0)} KB) <button type="button" className="chip" onClick={clear}>remove</button></div>
          {preview && <img className="preview" src={preview} alt="Selected upload preview" />}
        </>
      ) : (
        <div>Drop an image here or click to choose (JPEG / PNG / WEBP, max 8 MB)</div>
      )}
    </div>
  );
}

